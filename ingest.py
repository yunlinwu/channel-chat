"""
Build the search index. Runs on your laptop, never in production.

    python ingest.py                                      # use videos.txt
    python ingest.py --channel https://youtube.com/@you --limit 10

Output (both committed to git, both read by app.py):
    index.json  — chunk text + citation metadata
    index.npy   — the embedding matrix

Why precompute: embedding at request time would mean paying and waiting on every
question. The corpus doesn't change between deploys, so it belongs in the build.
"""

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from dotenv import load_dotenv

# Read .env (gitignored) so keys live on disk, not in your shell history.
load_dotenv(Path(__file__).parent / ".env")

from embeddings import MODEL, embed_texts
from youtube_transcript_mcp.transcript import (
    extract_video_id,
    get_transcript,
    get_video_metadata,
)

HERE = Path(__file__).parent
CHUNK_SIZE = 5  # transcript segments glued together per chunk


def read_videos_file() -> list[str]:
    lines = (HERE / "videos.txt").read_text().splitlines()
    return [ln.strip() for ln in lines if ln.strip() and not ln.startswith("#")]


def list_channel_videos(channel_url: str, limit: int) -> list[str]:
    """Ask yt-dlp for a channel's most recent video IDs, newest first."""
    url = channel_url.rstrip("/")
    if not url.endswith("/videos"):
        url += "/videos"
    proc = subprocess.run(
        ["yt-dlp", "--flat-playlist", "--print", "id",
         "--playlist-end", str(limit), url],
        capture_output=True, text=True, timeout=120,
    )
    if proc.returncode != 0:
        sys.exit(f"yt-dlp failed listing channel:\n{proc.stderr.strip()}")
    return [v for v in proc.stdout.split() if v][:limit]


CACHE = HERE / ".cache"


def fetch_cached(video_id: str) -> dict:
    """
    Transcript + title for one video, cached on disk.

    yt-dlp is the slow part of ingest and the result never changes, so a failed
    embedding run (or a re-chunk experiment) shouldn't pay for it twice.
    """
    CACHE.mkdir(exist_ok=True)
    path = CACHE / f"{video_id}.json"
    if path.exists():
        data = json.loads(path.read_text())
        data["cached"] = True
        return data

    title = get_video_metadata(video_id).get("title", video_id)
    result = get_transcript(video_id)
    data = {
        "title": title,
        "source": result.source,
        "segments": [s.to_dict() for s in result.segments],
        "cached": False,
    }
    path.write_text(json.dumps(data))
    return data


def chunk(segments: list[dict]) -> list[dict]:
    out = []
    for i in range(0, len(segments), CHUNK_SIZE):
        window = segments[i : i + CHUNK_SIZE]
        text = " ".join(s["text"] for s in window).strip()
        if not text:
            continue
        out.append({
            "text": text,
            "start": round(window[0]["start"], 2),
            "timestamp": window[0]["timestamp"],
        })
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--channel", help="channel URL; overwrites videos.txt")
    ap.add_argument("--limit", type=int, default=10)
    args = ap.parse_args()

    if args.channel:
        ids = list_channel_videos(args.channel, args.limit)
        (HERE / "videos.txt").write_text(
            "# Generated by ingest.py --channel\n" + "\n".join(ids) + "\n"
        )
        print(f"Wrote {len(ids)} video IDs to videos.txt")
    else:
        ids = [extract_video_id(v) for v in read_videos_file()]

    if not ids:
        sys.exit("No videos to index. Add IDs to videos.txt or pass --channel.")

    chunks: list[dict] = []
    for n, video_id in enumerate(ids, 1):
        print(f"[{n}/{len(ids)}] {video_id}", flush=True)
        try:
            data = fetch_cached(video_id)
        except Exception as exc:  # one bad video shouldn't kill the whole build
            print(f"    skipped: {exc}")
            continue
        pieces = chunk(data["segments"])
        for p in pieces:
            p["video_id"] = video_id
            p["title"] = data["title"]
        chunks.extend(pieces)
        tag = "cached" if data["cached"] else data["source"]
        print(f"    '{data['title'][:60]}' -> {len(pieces)} chunks ({tag})")

    if not chunks:
        sys.exit("No transcript chunks produced — nothing to index.")

    print(f"\nEmbedding {len(chunks)} chunks with {MODEL}...")
    vectors = embed_texts([c["text"] for c in chunks], input_type="document",
                          verbose=True)

    np.save(HERE / "index.npy", vectors)
    (HERE / "index.json").write_text(json.dumps({
        "model": MODEL,
        "dims": int(vectors.shape[1]),
        "built_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "video_count": len(set(c["video_id"] for c in chunks)),
        "chunks": chunks,
    }, indent=2))

    size_mb = (HERE / "index.npy").stat().st_size / 1e6
    print(f"\nIndexed {len(chunks)} chunks from "
          f"{len(set(c['video_id'] for c in chunks))} videos.")
    print(f"index.npy = {size_mb:.1f} MB, {vectors.shape[1]} dims. Commit both files.")


if __name__ == "__main__":
    main()
